"""propglsl.py -- the prop bench's height library, lifted into the exe.

props/props_v01/propview.html owns eleven height functions -- H_panel,
H_rib, H_screen, H_buttons, H_hazard, H_valve, H_seam, H_pipe, H_perf,
H_plain -- and the SDF and noise primitives under them.  They are what puts
a bolt in the corner of a plate, a rib every N millimetres and a countersunk
hole in a perforated sheet, and they are the whole of the difference between
the bench's props and a flat box with a colour on it.

THE BENCH BAKES THEM INTO AN ATLAS AND THE EXE CANNOT.  The sum: 37 props at 1024-2048 squared over three targets is 1.6 GB of
texture, and 512 squared -- which would fit -- has too few texels to hold a
bolt.  So the exe evaluates the same field PER FRAGMENT instead, in the
region-local metres props.c now carries on every vertex.  Same functions,
same constants, no texture at all.

AND IT IS EXTRACTED, NOT TRANSCRIBED, for the reason nativepack.py gives:
a hand copy is a second thing to keep in step with the first, and the first
one is still being edited on the bench.  Re-run this after any change to
LIB_GLSL.

    python tools/propglsl.py     ->  native/src/props_glsl.h

The three uniforms LIB_GLSL declares are not uniforms here.  uTPM is the
bench's texels per metre, which the exe answers with the fragment's own
screen density (fwidth), so detail fades out with distance instead of with
an atlas rect; uRim and uWear become plain globals the caller sets.  That
substitution is this file's only edit to the source text, and it is done by
matching the exact declaration lines so a change to them fails loudly here
rather than quietly in the shader.
"""
import io
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.join(ROOT, 'props', 'props_v01', 'propview.html')
OUT = os.path.join(ROOT, 'native', 'src', 'props_glsl.h')

# the three declarations that have to stop being uniforms, and what they
# become.  Matched literally: if the bench renames one, this raises.
UNIFORMS = [
    ('uniform float uTPM; uniform int uRim;',
     '/* propglsl.py: set per fragment, not per draw -- see the header */\n'
     'float uTPM; int uRim;'),
    ('uniform float uWear;',
     'float uWear;'),
]

# the functions the exe actually calls into.  Presence is the check that the
# extraction got the whole library rather than a truncated backtick.
# (glyph() is NOT here: it lives in BAKE_FS, which draws the readouts on
# top of the height field, and no H_ function calls it.)
WANT = ['H_panel', 'H_rib', 'H_screen', 'H_buttons', 'H_hazard', 'H_valve',
        'H_seam', 'H_pipe', 'H_perf', 'H_plain', 'H0', 'H', 'fbm', 'fcap',
        'sdB', 'sdR', 'sdA', 'cham', 'rndp', 'domep', 'boltp', 'vnoise',
        'h21', 'wx', 'triw', 'mat']


def extract(text):
    m = re.search(r'const LIB_GLSL = `(.*?)\n`;', text, re.S)
    if not m:
        raise SystemExit('propglsl: LIB_GLSL not found in %s' % SRC)
    return m.group(1)


def cstring(glsl):
    """One C string literal a line, so a shader compile error's line number
    is the line number in propview.html plus the offset this prints."""
    out = []
    for line in glsl.split('\n'):
        line = line.replace('\\', '\\\\').replace('"', '\\"')
        out.append('  "%s\\n"' % line)
    return '\n'.join(out)


def main():
    text = io.open(SRC, encoding='utf-8').read()
    glsl = extract(text)

    for old, new in UNIFORMS:
        if glsl.count(old) != 1:
            raise SystemExit('propglsl: %r appears %d times, expected 1'
                             % (old, glsl.count(old)))
        glsl = glsl.replace(old, new)

    missing = [w for w in WANT if not re.search(r'\b%s\s*\(' % w, glsl)]
    if missing:
        raise SystemExit('propglsl: extracted text is missing %s'
                         % ', '.join(missing))

    # GLSL ES 300 and GLSL 330 core differ in nothing this library uses --
    # no precision qualifiers, no texture2D, no ES-only builtins.  Assert it
    # rather than assume it.
    for bad in ('precision ', 'texture2D', 'gl_FragColor', 'lowp ', 'mediump '):
        if bad in glsl:
            raise SystemExit('propglsl: %r is GLSL ES only' % bad)

    body = cstring(glsl)
    hdr = (
        '/* GENERATED by tools/propglsl.py from props/props_v01/propview.html\n'
        '   -- do not edit.  %d lines of the bench\'s own height library,\n'
        '   spliced into the entity shader so a prop can be surfaced without\n'
        '   an atlas.  See the tool\'s docstring for the three uniforms that\n'
        '   stop being uniforms. */\n'
        '#ifndef PROPS_GLSL_H\n#define PROPS_GLSL_H\n\n'
        'static const char *PROPS_GLSL =\n%s;\n\n#endif\n'
        % (len(glsl.split('\n')), body))

    io.open(OUT, 'w', encoding='utf-8', newline='').write(hdr)
    print('props_glsl.h  %d lines of GLSL, %d bytes'
          % (len(glsl.split('\n')), len(hdr)))


if __name__ == '__main__':
    sys.exit(main())
