sub("  case OP.COPY:{ B.set(REGS[ins[2]]); break; }",
    r"""  case OP.COPY:{ B.set(REGS[ins[2]]); break; }

  /* ---- SOFT BOX: a rectangle with a feathered rim ----------------------
     args  cx cy | fx fy | hx hy | r g b | opacity=1 | curve=0.5
     Solid inside the half-size (hx,hy); beyond it the colour fades out over
     (fx,fy), measured as an ellipse so the corners round off.  The fade is
     1-q^(0.5/curve), q the squared reach into the rim.  The axes are
     separable, so the reach is worked out once per column and once per row.
     Both axes wrap, so the box tiles.  */
  case OP.GLOWR:{
    const c=[ins[2],ins[3]], f=[Math.max(1e-5,ins[4]),Math.max(1e-5,ins[5])],
          h=[ins[6],ins[7]], col=[ins[8],ins[9],ins[10]];
    const op=ins[11]===undefined?1:ins[11], curve=ins[12]===undefined?0.5:ins[12];
    const k=0.5/Math.max(1e-5,curve);
    const reach=axis=>{
      const out=new Float32Array(N);
      for(let t=0;t<N;t++){
        let a=Math.abs((t+0.5)/N-c[axis]);
        if(1-a<a) a=1-a;                      // the nearer copy on the torus
        a=Math.max(0,a-h[axis])/f[axis]; out[t]=a*a;
      }
      return out;
    };
    const qx=reach(0), qy=reach(1);
    for(let y=0;y<N;y++){
      if(qy[y]>=1) continue;
      for(let x=0;x<N;x++){
        const r2=qx[x]+qy[y];
        if(r2>=1) continue;
        const w=(1-Math.pow(r2,k))*op;
        if(w<=0) continue;
        const t=(y*N+x)*4;
        for(let ch=0;ch<3;ch++) B[t+ch]=mixf(B[t+ch],col[ch],w);
      }
    }
    break; }

  /* ---- WARP: the register seen through a turn, a scale and a shift -----
     Each output texel undoes the shift, the scale and the turn and reads
     the source there, bilinearly, on a torus so a warped tile still tiles. */
  case OP.XFORM:{
    const th=ins[2]*6.2831853, ct=Math.cos(th), st=Math.sin(th),
          isx=1/(ins[3]||1), isy=1/(ins[4]||1),
          tx=ins[5]===undefined?0.5:ins[5], ty=ins[6]===undefined?0.5:ins[6];
    const src=Float32Array.from(B);
    for(let y=0;y<N;y++){
      const py=(y+0.5)/N-0.5;
      for(let x=0;x<N;x++){
        const px=(x+0.5)/N-0.5;
        let u=( px*ct+py*st)*isx+tx, v=(-px*st+py*ct)*isy+ty;
        u-=Math.floor(u); v-=Math.floor(v);
        const fx=u*N-0.5, fy=v*N-0.5, bx=Math.floor(fx), by=Math.floor(fy);
        const wx=fx-bx, wy=fy-by;
        const x0=((bx%N)+N)%N, y0=((by%N)+N)%N, x1=(x0+1)%N, y1=(y0+1)%N;
        const a=(y0*N+x0)*4, b=(y0*N+x1)*4, cc=(y1*N+x0)*4, dd=(y1*N+x1)*4;
        const t=(y*N+x)*4;
        for(let ch=0;ch<3;ch++){
          const top=src[a+ch]+(src[b+ch]-src[a+ch])*wx,
                bot=src[cc+ch]+(src[dd+ch]-src[cc+ch])*wx;
          B[t+ch]=top+(bot-top)*wy;
        }
      }
    }
    break; }

  /* ---- REPEAT: 2^n copies by doubling ----------------------------------
     args  turn | sx sy | tx ty | how=add | n=1 | fade=1
     Lay the register over itself shifted one step: two copies.  Again,
     shifted two steps: four.  n passes give 2^n evenly spaced copies.
     (tx,ty) is where the LAST copy lands, so a step is that offset over
     2^n-1 and pass p moves 2^p steps; scale and fade compound the same
     way.  how: 0 add, 1 subtract, 2 multiply, 3 lighter. */
  case OP.XMUL:{
    const how=ins[7]|0, passes=Math.max(1,ins[8]|0);
    const copies=1<<passes, steps=copies-1;
    let turn=ins[2]/copies;
    const stepx=((ins[5]===undefined?0.5:ins[5])-0.5)/steps,
          stepy=((ins[6]===undefined?0.5:ins[6])-0.5)/steps;
    let gx=Math.pow(ins[3]||1,1/steps), gy=Math.pow(ins[4]||1,1/steps);
    let dim=ins[9]===undefined?1:ins[9];
    for(let p=0,span=1;p<passes;p++,span*=2){
      const keep=Float32Array.from(B);
      if(dim!==1) for(let i=0;i<B.length;i+=4){ B[i]*=dim; B[i+1]*=dim; B[i+2]*=dim; }
      runOp([OP.XFORM,d,turn,gx,gy,0.5+stepx*span,0.5+stepy*span]);
      for(let i=0;i<B.length;i+=4) for(let ch=0;ch<3;ch++){
        const a=keep[i+ch], b=B[i+ch];
        B[i+ch]= how===1? a-b : how===2? a*b : how===3? Math.max(a,b) : a+b;
      }
      turn*=2; gx*=gx; gy*=gy; dim*=dim;
    }
    break; }""", 'soft box, warp, repeat')

