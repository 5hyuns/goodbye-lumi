# ---- 8e2. the register the mask lives in ---------------------------------
#           Registers 0-3 are albedo, height, roughness and emissive; 4-7 are
#           scratch and every recipe clobbers them.  The mask needs one that
#           survives to the end of the program, so it gets its own: reg 8,
#           cleared to 0 like the rest, which is why silence means "use the
#           table value".
# ---- 8e3. the gloss ceiling ----------------------------------------------
#           190 is the tightest Blinn lobe this shader could make, and 190 is
#           a satin.  However low a recipe drove its roughness the highlight
#           stayed a soft smear, so a glossier recipe had nothing left to
#           pull on -- the limit was the exponent, not the material.
#
#           640 is a coated plate that returns a lamp as a SHAPE.  The curve
#           goes to a cube so the extra gloss lands only where the surface is
#           already smooth: at rough 0.11 the lobe goes 134 -> 424, and at
#           rough 0.5 -- concrete, grating, a matte pan -- it moves 56 -> 78
#           and nothing in the room changes character.  specNorm already
#           holds the lobe's energy fixed as it tightens, so this is sharper,
#           not brighter.
# ---- 8e4. a smooth surface has to SEE the room ---------------------------
#           The env term is Fresnel-weighted and a dielectric's F0 is 0.04,
#           so a mirror-smooth plate picked up four per cent of the ambient
#           cube -- the same four per cent as a matte one.  Gloss that only
#           exists in the specular lobe is gloss you can only see when a lamp
#           happens to be in the right place, which in a dead ship is almost
#           never.  Scaling the reflection by the same cubed smoothness gives
#           the plate its sheen back everywhere, and leaves grating, concrete
#           and matte pan within a tenth of where they were.
sub("  col+=env*Fe*ao*mix(1.0,2.0,metal);",
    "  col+=env*Fe*ao*mix(1.0,2.0,metal)*mix(1.0,3.0,pow(1.0-rough,3.0));",
    'env sheen')

