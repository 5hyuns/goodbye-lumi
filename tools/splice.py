def cut(a, b, new, label):
    """replace s[a_end : b_start] where a and b are unique anchors"""
    global s, n
    i = s.index(a) + len(a)
    j = s.index(b, i)
    s = s[:i] + new + s[j:]
    n += 1

def sub(old, new, label, count=1):
    global s, n
    assert s.count(old) >= count, 'anchor missing: ' + label
    s = s.replace(old, new, count)
    n += 1

