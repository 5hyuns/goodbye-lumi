# ---- 8e. NO NORMAL INSIDE THE NORMAL -------------------------------------
#          The shader re-tiled each material's own normal map six times over
#          as a near-field detail layer.  On a rough wall that is free grain;
#          on THIS set it is a ghost of the plate drawn inside the plate.
#          Every material here draws structure -- a seam, a chamfer, a bolt
#          -- so the re-tile does not add tooth, it adds a second, smaller
#          copy of the same seams, chamfers and bolts on top of the first.
#          Stand in a shell room and the 1.2 m bay has a 200 mm bay ghosted
#          across its face, lifting lugs and all.  Two passes of dialling it
#          down (0.25 -> 0.12, fade 8 m -> 5 m) only made the ghost fainter;
#          the answer is that a map that already contains structure must not
#          be used as its own detail map.
#
#          Taking it out frees the normal map's BLUE channel, which was pure
#          waste anyway: z is reconstructed from x and y exactly, because
#          the compiler writes a unit vector whose z is always positive.
#          That channel now carries a PER-TEXEL METAL MASK, which is what
#          lets one material hold both a painted face and a bare steel
#          border -- see `Bay plate` in shipmaterials.py.
sub("""  vec3 tn=Nm.rgb*2.0-1.0;
  // detail normal: the same map re-tiled fine, faded out with distance
  float detFade=1.0-smoothstep(1.5,8.0,camDist);
  vec3 dn=texture(uNrm,vec3(vUV*6.0,vTex)).rgb*2.0-1.0;
  tn.xy+=dn.xy*0.25*detFade;
  tn=normalize(tn);""",
"""  // z is not stored: the compiler wrote a unit vector, so x and y are all
  // it takes to get it back.  Blue is the metal mask instead.
  vec3 tn;
  tn.xy=Nm.xy*2.0-1.0;
  tn.z=sqrt(max(1.0-dot(tn.xy,tn.xy),1e-4));
  tn=normalize(tn);""", 'detail normal removed')

