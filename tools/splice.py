# ---- 9a. ONE UV RULE -----------------------------------------------------
#          The map had three projections and the shader had a fourth.  A box
#          face snapped u,w to whichever world axis its normal was not zero
#          on; a generated quad went through the same test, so a 45 deg
#          chamfer got the *wall's* projection squeezed by cos45 and a corner
#          cut got a projection that matched one of its two walls and broke
#          against the other; a smooth-shaded triangle picked its axis from the
#          largest component of a *smooth* normal, so the projection flipped
#          mid-surface and tore the part in half.  Meanwhile the shader built
#          its tangent frame from `abs(n) > 0.5`, which agrees with none of
#          them on any face that is not axis aligned -- so every bevel was
#          also lit with the wrong normal map orientation.
#
#          There is one rule now, and the mesher and the shader both use it:
#
#              T = normalize(cross(worldUp, n))   -- horizontal, along the face
