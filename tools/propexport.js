/* propexport.js -- runs the JS kit, records every builder call each
   prop makes with its arguments already resolved (so loops, computed
   coordinates and palette spreads all collapse to numbers), and emits
   C that replays them through propkit.c.

   Opts objects are deduplicated across the whole kit into one table,
   because the same {kind, seed, tint} recurs hundreds of times.

   Run:  node tools/propexport.js
         props/props_v01/propkit.js  ->  native/src/props_gen.c */
const fs=require('fs');
const path=require('path');
const ROOT=path.join(__dirname,'..');
const DST=path.join(ROOT,'native','src','props_gen.c');
/* CRLF from a Windows checkout would stop the two anchors below matching. */
let src=fs.readFileSync(path.join(ROOT,'props','props_v01','propkit.js'),'utf8').replace(/\r\n/g,'\n');
src=src.replace('  buildFn({','  buildFn(globalThis.__W({');
src=src.replace('  });\n\n  PROPS.push({ name, room','  }));\n\n  PROPS.push({ name, room');

const LOG=[];
const OPS=new Set(['box','plainBox','panel','face4','hullRing','capPoly','hull8','octBox',
  'loft','capRound','capBar','xbrace','rrFrame','boss','stack','tube','wheelZ','strap',
  'socket','ringAt','rectRing','revRing','octFoot','cutRing','roundRing','insetRing']);
/* ringAt/rectRing/... are PURE: they return points and draw nothing, so
   they are evaluated here and their results inlined as literals. Only
   the drawing calls become C. */
const PURE=new Set(['ringAt','rectRing','revRing','octFoot','cutRing','roundRing','insetRing']);
globalThis.__W=(o)=>new Proxy(o,{get(t,k){
  const v=t[k];
  if(typeof v!=='function'||!OPS.has(k)) return v;
  return (...a)=>{
    const r=v(...a);
    if(!PURE.has(k)) LOG.push({op:k,args:a});
    return r;
  };
}});
const vm=require('vm');
/* one pass only: the kit declares consts at top level, so running it a
   second time in the same context is a redeclaration error */
const marks=[];
globalThis.__MARK=(n)=>marks.push([n,LOG.length]);
const MARKED = src.replace('  PROPS.push({ name, room',
  '  globalThis.__MARK(name);\n  PROPS.push({ name, room');
vm.runInThisContext(MARKED);
const perProp=[];
{ let prev=0;
  for(const [n,end] of marks){ perProp.push({name:n,calls:LOG.slice(prev,end)}); prev=end; } }

/* ---- opts table ---- */
const optKey=o=>JSON.stringify({k:o&&o.kind, s:o&&o.seed, a:o&&o.accent,
  p:o&&o.params, t:o&&o.tint, pa:!!(o&&o.paint), r:!!(o&&o.rim),
  sh:o&&o.share===false?0:1, ti:!!(o&&o.tile), ch:o&&o.chamfer});
const optTab=[], optIx=new Map();
function opt(o){
  if(o===null||o===undefined) return -1;
  const k=optKey(o);
  if(optIx.has(k)) return optIx.get(k);
  const i=optTab.length; optTab.push(o); optIx.set(k,i); return i;
}
const f=v=>{ const s=(+v).toFixed(6).replace(/0+$/,'').replace(/\.$/,'.0'); return s+'f'; };
const v3=a=>`{${f(a[0])},${f(a[1])},${f(a[2])}}`;

/* walk every call so the table is built before emitting */
for(const P of perProp) for(const c of P.calls){
  const A=c.args;
  switch(c.op){
    case 'panel': opt(A[6]); break;
    case 'face4': opt(A[4]); break;
    case 'box': { const S=A[6]||{}; for(const k of ['px','nx','py','ny','pz','nz']) opt(S[k]); break; }
    case 'plainBox': opt(Object.assign({kind:7,seed:A[6]||7,chamfer:0},A[7]||{})); break;
    case 'octBox': case 'hull8': case 'loft': {
      const S=(c.op==='octBox'?A[7]:A[2])||{};
      for(const k of ['px','nz','nx','pz','py','ny','diag','trim']) opt(S[k]);
      if(typeof S.topOpts==='function'){ opt(S.topOpts(0)); opt(S.topOpts(1)); }
      else opt(S.topOpts);
      break; }
    case 'tube': { const O=A[3]||{}; opt(O.face); opt(O.capOpts); opt(O.collarOpts); break; }
    case 'stack': { for(const s of A[2]) opt(s.face); const O=A[3]||{}; opt(O.shoulder); opt(O.capOpts); break; }
    case 'capBar': opt(A[6]); break;
    case 'strap': opt(A[5]); break;
    case 'xbrace': opt(A[8]); break;
    case 'rrFrame': opt(A[9]); break;
    case 'boss': { const O=A[4]||{}; opt(O.face); opt(O.cap); break; }
    case 'hullRing': opt(A[2]); break;
    case 'capPoly': opt(A[1]); break;
    case 'wheelZ': break;
    case 'socket': break;
  }
}
console.error('props',perProp.length,'calls',perProp.reduce((a,p)=>a+p.calls.length,0),'opts',optTab.length);

let out=[];
out.push('/* GENERATED by propexport.js -- do not edit. */');
out.push('#include "propkit.h"');
out.push('#include <stddef.h>\n');
out.push('static PkOpts OPT['+optTab.length+'];');
out.push('static const float TINTS[][3]={');
const tintTab=[], tintIx=new Map();
for(const o of optTab) if(o&&o.tint){ const k=o.tint.join(','); if(!tintIx.has(k)){ tintIx.set(k,tintTab.length); tintTab.push(o.tint);} }
for(const t of tintTab) out.push('  '+v3(t)+',');
out.push('};');
out.push('static void optInit(void){');
out.push('  for(int i=0;i<'+optTab.length+';i++) OPT[i]=pkOpts();');
optTab.forEach((o,i)=>{
  const L=[];
  if(o.kind!==undefined) L.push(`OPT[${i}].kind=${o.kind};`);
  if(o.seed!==undefined) L.push(`OPT[${i}].seed=${f(o.seed)};`);
  if(o.accent!==undefined) L.push(`OPT[${i}].accent=${o.accent};`);
  if(o.params){ L.push(`OPT[${i}].hasParams=1;`);
    o.params.forEach((p,j)=>{ if(p) L.push(`OPT[${i}].params[${j}]=${f(p)};`); }); }
  if(o.tint) L.push(`OPT[${i}].tint=TINTS[${tintIx.get(o.tint.join(','))}];`);
  if(o.paint) L.push(`OPT[${i}].paint=1;`);
  if(o.rim) L.push(`OPT[${i}].rim=1;`);
  if(o.share===false) L.push(`OPT[${i}].share=0;`);
  if(o.tile) L.push(`OPT[${i}].tile=1;`);
  if(o.chamfer!==undefined) L.push(`OPT[${i}].chamfer=${f(o.chamfer)};`);
  if(L.length) out.push('  '+L.join(' '));
});
out.push('}');
const O=i=>i<0?'NULL':`&OPT[${i}]`;

perProp.forEach((P,pi)=>{
  out.push(`\n/* ${P.name} */`);
  out.push(`static void build${pi}(void){`);
  let tmp=0;
  for(const c of P.calls){
    const A=c.args;
    switch(c.op){
      case 'panel':
        out.push(`  { const float O[3]=${v3(A[0])},U[3]=${v3(A[1])},V[3]=${v3(A[2])},N[3]=${v3(A[3])};`
          +` pkPanel(O,U,V,N,${f(A[4])},${f(A[5])},${O(opt(A[6]))}); }`); break;
      case 'face4':
        out.push(`  { const float a[3]=${v3(A[0])},b[3]=${v3(A[1])},c[3]=${v3(A[2])},d[3]=${v3(A[3])};`
          +` pkFace4(a,b,c,d,${O(opt(A[4]))}); }`); break;
      case 'box': { const S=A[6]||{};
        out.push(`  pkBoxSides(${f(A[0])},${f(A[1])},${f(A[2])},${f(A[3])},${f(A[4])},${f(A[5])},`
          +['px','nx','py','ny','pz','nz'].map(k=>O(opt(S[k]))).join(',')+`);`); break; }
      case 'plainBox': {
        const e=A[7]||{};
        out.push(`  pkPlainBox(${f(A[0])},${f(A[1])},${f(A[2])},${f(A[3])},${f(A[4])},${f(A[5])},`
          +`${f(A[6]||7)},${e.tint?`TINTS[${tintIx.get(e.tint.join(','))}]`:'NULL'},${e.paint?1:0});`);
        break; }
      case 'octBox': case 'hull8': case 'loft': {
        const S=(c.op==='octBox'?A[7]:A[2])||{};
        const nm='L'+(tmp++);
        out.push(`  { PkLoft ${nm}=pkLoft0();`);
        for(const k of ['px','nz','nx','pz','py','ny','diag','trim'])
          if(S[k]!==undefined) out.push(`    ${nm}.${k}=${O(opt(S[k]))};`);
        if(typeof S.topOpts==='function'){
          out.push(`    ${nm}.topOpts=${O(opt(S.topOpts(0)))}; ${nm}.topOptsAlt=${O(opt(S.topOpts(1)))};`);
        } else if(S.topOpts!==undefined) out.push(`    ${nm}.topOpts=${O(opt(S.topOpts))};`);
        if(S.cut!==undefined) out.push(`    ${nm}.cut=${f(S.cut)};`);
        if(S.topCut!==undefined) out.push(`    ${nm}.topCut=${f(S.topCut)};`);
        if(S.topRound!==undefined) out.push(`    ${nm}.topRound=${f(S.topRound)};`);
        if(S.seg!==undefined) out.push(`    ${nm}.seg=${S.seg};`);
        if(S.topSeg!==undefined) out.push(`    ${nm}.topSeg=${S.topSeg};`);
        if(S.facet) out.push(`    ${nm}.facet=1;`);
        if(c.op==='octBox')
          out.push(`    pkOctBox(${f(A[0])},${f(A[1])},${f(A[2])},${f(A[3])},${f(A[4])},${f(A[5])},${f(A[6])},&${nm}); }`);
        else {
          out.push(`    const float B[4][3]={${A[0].map(v3).join(',')}};`);
          out.push(`    const float T[4][3]={${A[1].map(v3).join(',')}};`);
          out.push(`    ${c.op==='hull8'?'pkHull8':'pkLoft'}(B,T,&${nm}); }`);
        }
        break; }
      case 'tube': { const Q=A[3]||{}; const nm='T'+(tmp++);
        out.push(`  { PkTube ${nm}=pkTube0();`);
        if(Q.n) out.push(`    ${nm}.n=${Q.n};`);
        if(Q.phase!==undefined) out.push(`    ${nm}.phase=${f(Q.phase)};`);
        if(Q.face) out.push(`    ${nm}.face=${O(opt(Q.face))};`);
        if(Q.capOpts) out.push(`    ${nm}.capOpts=${O(opt(Q.capOpts))};`);
        if(Q.collarOpts) out.push(`    ${nm}.collarOpts=${O(opt(Q.collarOpts))};`);
        if(Q.capA) out.push(`    ${nm}.capA=1;`);
        if(Q.capB) out.push(`    ${nm}.capB=1;`);
        if(Q.collar){ if(Q.collar.indexOf('a')>=0) out.push(`    ${nm}.collarA=1;`);
                      if(Q.collar.indexOf('b')>=0) out.push(`    ${nm}.collarB=1;`); }
        if(Q.collarR) out.push(`    ${nm}.collarR=${f(Q.collarR)};`);
        if(Q.collarL) out.push(`    ${nm}.collarL=${f(Q.collarL)};`);
        if(Q.capRoll!==undefined) out.push(`    ${nm}.capRoll=${f(Q.capRoll)};`);
        out.push(`    const float p0[3]=${v3(A[0])},p1[3]=${v3(A[1])};`);
        out.push(`    pkTubeDraw(p0,p1,${f(A[2])},&${nm}); }`);
        break; }
      case 'stack': { const Q=A[3]||{}; const nm='S'+(tmp++);
        out.push(`  { PkSect ${nm}[${A[2].length}]={0};`);
        A[2].forEach((s,j)=>{
          out.push(`    ${nm}[${j}].l=${f(s.l)}; ${nm}[${j}].r=${f(s.r)};`
            +(s.face?` ${nm}[${j}].hasFace=1; ${nm}[${j}].face=OPT[${opt(s.face)}];`:''));
        });
        out.push(`    PkStack O${nm}=pkStack0();`);
        if(Q.n) out.push(`    O${nm}.n=${Q.n};`);
        if(Q.shoulder) out.push(`    O${nm}.shoulder=${O(opt(Q.shoulder))};`);
        if(Q.capOpts) out.push(`    O${nm}.capOpts=${O(opt(Q.capOpts))};`);
        if(Q.capA===false) out.push(`    O${nm}.noCapA=1;`);
        if(Q.capB===false) out.push(`    O${nm}.noCapB=1;`);
        out.push(`    const float b[3]=${v3(A[0])},ax[3]=${v3(A[1])};`);
        out.push(`    pkStackDraw(b,ax,${nm},${A[2].length},&O${nm}); }`);
        break; }
      case 'capBar': case 'strap': {
        const isS=c.op==='strap';
        const a=A[0],b=A[1],w=A[2],t=A[3],N=A[4];
        const seg=isS?4:A[5], o=isS?A[5]:A[6];
        out.push(`  { const float a[3]=${v3(a)},b[3]=${v3(b)},N[3]=${v3(N)};`
          +` pkCapBar(a,b,${f(w)},${f(t)},N,${isS?4:seg},${O(opt(o))}); }`); break; }
      case 'xbrace':
        out.push(`  { const float O_[3]=${v3(A[0])},U[3]=${v3(A[1])},V[3]=${v3(A[2])},N[3]=${v3(A[3])};`
          +` pkXBrace(O_,U,V,N,${f(A[4])},${f(A[5])},${f(A[6])},${f(A[7])},${O(opt(A[8]))}); }`); break;
      case 'rrFrame': {
        const o=A[9]||{};
        out.push(`  { const float O_[3]=${v3(A[0])},U[3]=${v3(A[1])},V[3]=${v3(A[2])},N[3]=${v3(A[3])};`
          +` pkRRFrame(O_,U,V,N,${f(A[4])},${f(A[5])},${f(A[6])},${f(A[7])},${f(A[8])},`
          +`${O(opt(A[9]))},${o.seg||0}); }`); break; }
      case 'boss': { const Q=A[4]||{}; const nm='B'+(tmp++);
        out.push(`  { PkBoss ${nm}=pkBoss0();`);
        if(Q.n) out.push(`    ${nm}.n=${Q.n};`);
        if(Q.fillet!==undefined) out.push(`    ${nm}.fillet=${f(Q.fillet)};`);
        if(Q.seed!==undefined) out.push(`    ${nm}.seed=${f(Q.seed)};`);
        if(Q.filletSeg) out.push(`    ${nm}.filletSeg=${Q.filletSeg};`);
        if(Q.face) out.push(`    ${nm}.face=${O(opt(Q.face))};`);
        if(Q.cap) out.push(`    ${nm}.cap=${O(opt(Q.cap))};`);
        out.push(`    const float c[3]=${v3(A[0])},ax[3]=${v3(A[1])};`);
        out.push(`    pkBossDraw(c,ax,${f(A[2])},${f(A[3])},&${nm}); }`);
        break; }
      case 'hullRing': {
        const A0=A[0],B0=A[1];
        out.push(`  { const float A_[${A0.length}][3]={${A0.map(v3).join(',')}};`);
        out.push(`    const float B_[${B0.length}][3]={${B0.map(v3).join(',')}};`);
        const sm=A[3]===true?'PK_SMOOTH':(A[3]==='bevel'?'PK_BEVELMODE':'PK_FLAT');
        out.push(`    pkHullRing(A_,B_,${A0.length},${O(opt(A[2]))},${sm}); }`); break; }
      case 'capPoly':
        out.push(`  { const float R_[${A[0].length}][3]={${A[0].map(v3).join(',')}};`
          +` pkCapPoly(R_,${A[0].length},${O(opt(A[1]))}); }`); break;
      case 'wheelZ': { const Q=A[6]||{};
        out.push(`  pkWheelZ(${f(A[0])},${f(A[1])},${f(A[2])},${f(A[3])},${f(A[4])},${f(A[5])},`
          +`${f(Q.seed||11)},${Q.tint?`TINTS[${tintIx.get(Q.tint.join(','))}]`:'NULL'},${Q.paint?1:0},`
          +`${f(Q.hub||0)},${f(Q.spoke||0)});`); break; }
      case 'socket':
        out.push(`  { const float p[3]=${v3(A[1])},d[3]=${v3(A[2]||[0,0,1])};`
          +` pkSocket("${A[0]}",p,d); }`); break;
    }
  }
  out.push('}');
});

/* PkBuildFn is declared in propkit.h, beside PK_BUILD's extern. */
out.push('');
out.push('const PkBuildFn PK_BUILD['+perProp.length+']={'+perProp.map((_,i)=>'build'+i).join(',')+'};');
out.push('const char *const PK_NAME['+perProp.length+']={'+perProp.map(p=>JSON.stringify(p.name)).join(',')+'};');
out.push('const int PK_COUNT='+perProp.length+';');
out.push('void pkBuildProp(int i){ static int once=0; if(!once){ optInit(); once=1; } pkBegin(); if(i>=0&&i<PK_COUNT) PK_BUILD[i](); }');
fs.writeFileSync(DST,out.join('\n')+'\n');
console.error('wrote', path.relative(ROOT,DST), fs.statSync(DST).size, 'bytes');
